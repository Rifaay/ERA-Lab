import { useEffect, useRef } from "react";
import { getAthletes, getSessions, getReviews, saveReview, getRange } from "../storage";
import { reviewFromLabels, mergeReview } from "../review";
import { mountLabeller } from "../review/engine";
import { MARKUP } from "../review/markup";
import { translateMarkup, reviewText, faultText } from "../review/i18n";
import "../review/review.css";

// Video review: mark the shot's phases and faults on a clip, and link the clip to its arrow.
// The tool itself is the Labeller, mounted here as it is. This screen connects it to the app's records:
// range sessions go in (so a clip can find its end), a clip copied from the phone brings its quick tags,
// each saved review comes back out, and everything it says is in the coach's language.
export default function Review({ selectedId, guardRef, lang, tr }) {
  const hostRef = useRef(null);
  const archerRef = useRef(selectedId);
  useEffect(() => { archerRef.current = selectedId; }, [selectedId]); // the tool mounts once; saving must see the archer chosen now
  const faultNames = tr.quick.faults;

  useEffect(() => {
    const host = hostRef.current;
    host.innerHTML = translateMarkup(MARKUP, lang); // our own static layout, generated by scripts/port-labeller.py
    const tool = mountLabeller(host, {
      sessions: () => [...getSessions().filter((s) => s.range).map((s) => s.range), ...(getRange().live ? [getRange().live] : [])],
      review: (clipName) => getReviews().find((r) => r.id === clipName) || null,
      onSaved: (labels) => {
        const next = reviewFromLabels(labels, { sessions: getSessions(), athletes: getAthletes(), selectedId: archerRef.current });
        saveReview(mergeReview(getReviews().find((r) => r.id === next.id), next));
      },
      t: reviewText(lang), fault: faultText(lang, faultNames), lang,
    });
    guardRef.current = tool.isDirty; // lets the app ask before leaving with unsaved labels
    return () => { guardRef.current = null; tool.destroy(); host.innerHTML = ""; };
  }, [guardRef, lang, faultNames]); // shortcut: switching language here starts the tool again, like leaving and coming back

  return <div className="lab-host" ref={hostRef} />;
}
